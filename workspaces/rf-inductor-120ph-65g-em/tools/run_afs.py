"""Retain and run an explicit native Momentum AFS profile without resampling.

The native exporter must supply one of two strict 5-200 GHz profiles: r1 uses
50 adaptive plus four forced points; r2 uses 48 adaptive plus six forced points.
The original export, base exact-point preparation, and AFS
amendment are retained before execution. Actual EM samples and ADS-generated
dense rational-model samples are exported separately and labeled accordingly.
This helper never fits, extrapolates, repairs, or resamples a network itself.
"""

from __future__ import annotations

import argparse
import csv
from datetime import datetime, timezone
import io
import json
import math
from pathlib import Path
import re
import shutil
from typing import Any

from convert_cti import SNetwork, write_touchstone
from run_momentum import DATASET_NAME, RunError, _json, _sha, _verify_completion, prepare_case, run_case


NUMERIC = r"[+\-]?(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+)(?:[Ee][+\-]?[0-9]+)?"
PROFILE_NAME = "native-afs-5-to-200-forced-10-65-80-100-r1"
ADAPTIVE_SAMPLE_BUDGET = 50
FORCED_POINTS_GHZ = (10.0, 65.0, 80.0, 100.0)
# Preserve the original r1 constants and exact profile dictionary shape for
# already retained receipts. A new profile never upgrades or relabels r1 data.
NATIVE_PROFILES = {
    FORCED_POINTS_GHZ: {"name": PROFILE_NAME, "adaptive_sample_budget": ADAPTIVE_SAMPLE_BUDGET},
    (10.0, 20.0, 40.0, 65.0, 80.0, 100.0): {
        "name": "native-afs-5-to-200-forced-10-20-40-65-80-100-r2", "adaptive_sample_budget": 48},
}


def _utc() -> str:
    return datetime.now(timezone.utc).isoformat()


def validate_native_stimulus(text: str) -> dict[str, Any]:
    """Accept only the specified profile generated by the native exporter.

    This is validation of the retained native format, not a generator for
    undocumented stimulus grammar. S_50 is preserved as the exported response
    selector; it must never be replaced by an output-point count.
    """
    text = "\n".join(line for line in text.splitlines() if not line.strip().startswith("#"))
    statements = [statement.strip() for statement in text.split(";") if statement.strip()]
    if len(statements) != 1:
        raise RunError("The observed native AFS profile is one semicolon-terminated statement")
    clauses = [clause.strip() for clause in statements[0].split(",")]
    if len(clauses) not in {len(points) + 2 for points in NATIVE_PROFILES}:
        raise RunError("Native AFS profile requires the exact four-point r1 or six-point r2 forced plan")
    prefix = rf"START\s+({NUMERIC})\s+STOP\s+({NUMERIC})\s+STEP\s+({NUMERIC})"
    head = re.fullmatch(prefix, clauses[0], re.I)
    if head is None:
        raise RunError("Native AFS range has unexpected syntax")
    start, stop, step = map(float, head.groups())
    if (start, stop, step) != (5.0, 200.0, 195.0):
        raise RunError("Native AFS range must preserve the observed 5-200 GHz range and 195 GHz native step")
    forced = []
    for clause in clauses[1:-1]:
        point = re.fullmatch(rf"PT\s+({NUMERIC})", clause, re.I)
        if point is None:
            raise RunError("Native AFS forced-frequency clause has unexpected syntax")
        forced.append(float(point.group(1)))
    profile_definition = NATIVE_PROFILES.get(tuple(forced))
    if profile_definition is None:
        raise RunError("Native AFS forced points do not match the exact ordered r1 or r2 profile")
    tail = re.fullmatch(r"AFS\s+S_50\s+MAXSAMPLES\s+([0-9]+)\s+SAMPLING\s+ALL\s+NORMAL", clauses[-1], re.I)
    if tail is None:
        raise RunError("Native AFS response selector, sampling mode, or cap has unexpected syntax")
    total_cap = int(tail.group(1))
    adaptive_budget = profile_definition["adaptive_sample_budget"]
    expected_cap = adaptive_budget + len(forced)
    if total_cap != expected_cap:
        raise RunError("Native combined cap must preserve 54 total points: r1 is 50+4 and r2 is 48+6")
    adaptive_plan = {"start_GHz": start, "stop_GHz": stop, "native_step_GHz": step,
                     "selector": "S_50", "adaptive_sample_budget": adaptive_budget,
                     "forced_point_count": len(forced), "exported_combined_maximum_samples": total_cap,
                     "sampling": "ALL NORMAL"}
    return {"name": profile_definition["name"], "adaptive": adaptive_plan,
            "required_exact_GHz": [65.0, 80.0], "forced_exact_GHz": forced,
            "band_GHz": [5.0, 200.0], "dense_grid": "ADS-generated; spacing is observed, not assumed",
            "target_and_thresholds_changed": False}


def prepare_afs_case(export_dir: str | Path, outdir: str | Path, mesh_um: float,
                     ads_root: str | Path, threads: int = 4, *,
                     native_workspace: str | Path) -> dict[str, Any]:
    """Prepare a fresh case and retain a complete, explicit profile amendment."""
    source = Path(export_dir).resolve(strict=True)
    # Validate the actual native export before allocating any new run directory.
    native_stimulus = source / "proj.sti"
    profile = validate_native_stimulus(native_stimulus.read_text(encoding="utf-8-sig"))
    prepared = prepare_case(source, outdir, mesh_um, [65.0, 80.0], ads_root, threads,
                            native_workspace=native_workspace)
    case = Path(outdir).resolve(strict=True)
    retained = case / "pre-afs-amendment"
    retained.mkdir()
    shutil.copy2(case / "prepared-case.json", retained / "prepared-case.json")
    shutil.copy2(case / "proj.sti", retained / "proj.sti")
    shutil.copy2(case / "prepared-inputs" / "proj.sti", retained / "prepared-inputs-proj.sti")
    old_receipt = _sha(retained / "prepared-case.json")
    old_stimulus = _sha(retained / "proj.sti")
    original = case / "original-export" / "proj.sti"
    # Preserve the native bytes without rebuilding or interpreting a new plan.
    shutil.copy2(original, case / "proj.sti")
    shutil.copy2(original, case / "prepared-inputs" / "proj.sti")
    if _sha(original) != _sha(case / "proj.sti") or _sha(original) != _sha(case / "prepared-inputs" / "proj.sti"):
        raise RunError("Native AFS stimulus was not copied with exact byte identity")
    validate_native_stimulus((case / "proj.sti").read_text(encoding="utf-8-sig"))
    prepared["files"]["proj.sti"] = _sha(case / "proj.sti")
    prepared["frequency_profile"] = profile
    prepared["frequencies_GHz"] = [65.0, 80.0]
    prepared["frequency_profile_amendment"] = "afs-profile-amendment.json"
    prepared["base_exact_preparation_receipt"] = "pre-afs-amendment/prepared-case.json"
    # The complete old receipt and old exact stimulus are preserved above.
    (case / "prepared-case.json").write_text(json.dumps(prepared, indent=2, allow_nan=False) + "\n",
                                            encoding="utf-8", newline="\n")
    _json(case / "afs-profile-amendment.json", {
        "schema_version": 1, "created_utc": _utc(), "profile": profile,
        "reason": (f"Use retained native profile {profile['name']} with forced frequencies {profile['forced_exact_GHz']} GHz, "
                   f"the exported combined cap of {profile['adaptive']['adaptive_sample_budget']} adaptive plus "
                   f"{profile['adaptive']['forced_point_count']} forced points, and separate discrete/dense outputs"),
        "old_prepared_receipt": old_receipt, "amended_prepared_receipt": _sha(case / "prepared-case.json"),
        "old_exact_stimulus": old_stimulus, "native_afs_stimulus": _sha(original),
        "retained_before_amendment": "pre-afs-amendment", "source_export_modified": False,
        "thresholds_relaxed": False, "native_dense_grid_spacing_is_unconfirmed": True,
    })
    return prepared


def _verify_profile(case: Path) -> dict[str, Any]:
    prepared = json.loads((case / "prepared-case.json").read_text(encoding="utf-8"))
    amendment = json.loads((case / "afs-profile-amendment.json").read_text(encoding="utf-8"))
    profile = validate_native_stimulus((case / "proj.sti").read_text(encoding="utf-8-sig"))
    if profile != prepared.get("frequency_profile") or profile != amendment.get("profile"):
        raise RunError("AFS profile or amendment differs from the native retained stimulus")
    if amendment["amended_prepared_receipt"] != _sha(case / "prepared-case.json"):
        raise RunError("Prepared AFS receipt changed after the pre-run amendment")
    if amendment["old_prepared_receipt"] != _sha(case / "pre-afs-amendment" / "prepared-case.json"):
        raise RunError("Original exact-point preparation receipt is missing or changed")
    if amendment["old_exact_stimulus"] != _sha(case / "pre-afs-amendment" / "proj.sti"):
        raise RunError("Original exact-point stimulus is missing or changed")
    if amendment["native_afs_stimulus"] != _sha(case / "proj.sti"):
        raise RunError("Native AFS stimulus changed after the amendment")
    return prepared


def run_afs_case(case_dir: str | Path, ads_root: str | Path | None = None,
                 *, export_model: bool = True) -> dict[str, Any]:
    """Run synchronously with the base runner's serial lock and fullwave checks."""
    case = Path(case_dir).resolve(strict=True)
    _verify_profile(case)
    receipt = run_case(case, ads_root, export_model=False)
    if export_model:
        export_afs(case)
    return receipt


def _read_network(dataset_module: Any, source: Path) -> tuple[SNetwork, list[dict[str, Any]]]:
    raw = dataset_module.open(str(source))
    table = raw["data"].to_dataframe().reset_index()
    port_table = raw["ports"].to_dataframe().reset_index()
    expected_s = {"S[1,1]", "S[1,2]", "S[2,1]", "S[2,2]"}
    expected_z = {"PORTZ[1]", "PORTZ[2]"}
    if ("freq" not in table.columns
            or {str(column) for column in table.columns if str(column).startswith("S[")} != expected_s
            or {str(column) for column in table.columns if str(column).startswith("PORTZ[")} != expected_z):
        raise RunError("AFS export requires the complete two-port matrix and exactly two reference impedances")
    if len(port_table) != 2 or not {"Ports", "PlusPins", "MinusPins"}.issubset(set(port_table.columns)):
        raise RunError("AFS dataset has missing or extra physical port metadata")
    port_records = []
    for number, (_, row) in enumerate(port_table.iterrows(), 1):
        record = {key: str(row[key]).strip() for key in ("Ports", "PlusPins", "MinusPins")}
        if record != {"Ports": f"P{number}", "PlusPins": f"P{number}", "MinusPins": "P4"}:
            raise RunError("AFS dataset physical return or signal mapping differs from the frozen model")
        port_records.append({"number": number, **record, "reference_ohm": 50.0})
    for column in expected_z:
        if any(complex(value) != 50 + 0j for value in table[column]):
            raise RunError("AFS dataset has non-50-ohm or complex references")
    frequencies = tuple(float(value) for value in table["freq"])
    if (not frequencies or any(not math.isfinite(value) or value <= 0 for value in frequencies)
            or any(a >= b for a, b in zip(frequencies, frequencies[1:]))):
        raise RunError("AFS dataset frequencies are nonfinite, duplicated, or not increasing")
    if not math.isclose(frequencies[0], 5e9, rel_tol=1e-12, abs_tol=0.1) or not math.isclose(frequencies[-1], 200e9, rel_tol=1e-12, abs_tol=0.1):
        raise RunError("AFS dataset does not cover its declared 5-200 GHz endpoints")
    matrices = tuple(tuple(tuple(complex(row[f"S[{i},{j}]"]) for j in (1, 2)) for i in (1, 2))
                     for _, row in table.iterrows())
    network = SNetwork(frequencies, matrices, source.stem)
    # Use the shared independent writer to validate every complex entry before
    # creating any output file. It rejects nonfinite values and dimension loss.
    write_touchstone(network, io.StringIO(), 50.0)
    return network, port_records


def _render_network(network: SNetwork, *, derived: bool) -> str:
    buffer = io.StringIO()
    write_touchstone(network, buffer, 50.0)
    lines = buffer.getvalue().splitlines()
    lines[0] = ("! ADS-native AFS rational-model samples: derived interpolation, not discrete EM solves."
                if derived else "! Complete actual discrete Momentum EM samples; no interpolation or fitting by this exporter.")
    return "\n".join(lines) + "\n"


def export_afs(case_dir: str | Path) -> dict[str, Any]:
    """Export actual raw samples and native ADS dense-model samples separately."""
    case = Path(case_dir).resolve(strict=True)
    prepared = _verify_profile(case)
    profile = prepared["frequency_profile"]
    _verify_completion(case)
    if any((case / name).exists() for name in ("raw-discrete.s2p", "raw-complex-s.csv", "dense-afs.s2p", "afs-model-receipt.json")):
        raise RunError("An AFS export already exists; retain earlier artifacts rather than overwrite")
    actual_source = case / f"{DATASET_NAME}.ds"
    dense_source = case / f"{DATASET_NAME}_a.ds"
    if not dense_source.is_file() or dense_source.stat().st_size == 0:
        raise RunError("ADS-generated dense _a dataset is absent; no substitute interpolation will be invented")
    # Delayed API import keeps preparation, validation, and --help independent
    # of an installed ADS Python environment.
    from keysight.ads import dataset

    actual, ports = _read_network(dataset, actual_source)
    dense, dense_ports = _read_network(dataset, dense_source)
    if ports != dense_ports:
        raise RunError("Actual and dense AFS datasets have inconsistent port definitions")
    for frequency in (point * 1e9 for point in profile["forced_exact_GHz"]):
        if not any(math.isclose(value, frequency, rel_tol=1e-12, abs_tol=0.1) for value in actual.frequencies_hz):
            raise RunError("The actual EM dataset lacks a forced exact frequency required by its retained native profile")
    discrete_path, dense_path = case / "raw-discrete.s2p", case / "dense-afs.s2p"
    with discrete_path.open("x", encoding="ascii", newline="\n") as stream:
        stream.write(_render_network(actual, derived=False))
    with dense_path.open("x", encoding="ascii", newline="\n") as stream:
        stream.write(_render_network(dense, derived=True))
    csv_path = case / "raw-complex-s.csv"
    with csv_path.open("x", encoding="ascii", newline="") as stream:
        writer = csv.writer(stream)
        writer.writerow(["frequency_hz"] + [key for i in (1, 2) for j in (1, 2)
                                            for key in (f"S{i}{j}_real", f"S{i}{j}_imag")])
        for frequency, matrix in zip(actual.frequencies_hz, actual.s):
            writer.writerow([format(frequency, ".17g")] + [format(value, ".17g") for row in matrix for z in row for value in (z.real, z.imag)])
    frozen_grid_GHz = list(range(5, 101)) + list(range(105, 201, 5))
    missing_native_grid = [frequency for frequency in frozen_grid_GHz
                           if not any(math.isclose(value, frequency * 1e9, rel_tol=1e-12, abs_tol=0.1)
                                      for value in dense.frequencies_hz)]
    log = (case / "solver-console.log").read_text(encoding="utf-8", errors="replace")
    markers = [phrase for phrase in ("Maximum number of adaptive frequency samples reached",
                                     "Fitting models not (completely) converged", "AFS continuity problem",
                                     "frequency range not completely covered", "maximal refining depth")
               if phrase.lower() in log.lower()]
    receipt = {
        "schema_version": 1, "created_utc": _utc(), "frequency_profile": profile["name"],
        "frequency_profile_details": profile,
        "ports": ports, "actual_EM_dataset": actual_source.name, "actual_EM_samples_hz": list(actual.frequencies_hz),
        "raw_discrete_network": discrete_path.name, "native_raw_smatrixio": "proj.sio",
        "derived_ADS_dense_dataset": dense_source.name, "derived_ADS_dense_network": dense_path.name,
        "derived_ADS_dense_frequency_hz": list(dense.frequencies_hz),
        "dense_grid_maximum_step_hz": max((b - a for a, b in zip(dense.frequencies_hz, dense.frequencies_hz[1:])), default=0),
        "dense_native_grid_contains_frozen_display_points": not missing_native_grid,
        "frozen_display_points_missing_from_native_dense_grid_GHz": missing_native_grid,
        "self_fitting": False, "self_interpolation_or_resampling": False, "extrapolation": False,
        "renormalization": False, "passivity_repair": False,
        "AFS_warning_markers": markers,
        "AFS_status": "REQUIRES_CONVERGENCE_INVESTIGATION" if markers else "NO_LISTED_FAILURE_MARKER_OBSERVED_REQUIRES_INDEPENDENT_VALIDATION",
        "numerical_qualification": "PENDING: validate exact 65/80, tracked extrema, mesh/ports/returns, low frequency, and independent reproduction",
        "below_5_GHz": "Outside this adaptive profile; separate low-frequency evidence is required",
        "device_target_result": "NOT_DECIDED_BY_EXPORT", "parent_filter_acceptance": "NOT EVALUATED",
        "files": {path.name: _sha(path) for path in (actual_source, dense_source, case / "proj.sio", discrete_path, dense_path, csv_path)},
        "prepared_case_receipt": _sha(case / "prepared-case.json"),
        "profile_amendment_receipt": _sha(case / "afs-profile-amendment.json"),
        "execution_receipt": _sha(case / "execution-receipt.json"),
    }
    _json(case / "afs-model-receipt.json", receipt)
    return receipt


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)
    prepare = subparsers.add_parser("prepare", help="Retain and amend a fresh native exported AFS case")
    prepare.add_argument("export_dir", type=Path)
    prepare.add_argument("outdir", type=Path)
    prepare.add_argument("--mesh-um", type=float, required=True)
    prepare.add_argument("--ads-root", type=Path, required=True)
    prepare.add_argument("--native-workspace", type=Path, required=True)
    prepare.add_argument("--threads", type=int, default=4)
    solve = subparsers.add_parser("solve", help="Run the retained native profile synchronously and export both outputs")
    solve.add_argument("case_dir", type=Path)
    solve.add_argument("--ads-root", type=Path)
    solve.add_argument("--skip-export", action="store_true")
    export = subparsers.add_parser("export", help="Export completed actual/dense AFS results with separate provenance")
    export.add_argument("case_dir", type=Path)
    args = parser.parse_args()
    if args.command == "prepare":
        prepare_afs_case(args.export_dir, args.outdir, args.mesh_um, args.ads_root, args.threads,
                         native_workspace=args.native_workspace)
        print("Prepared the retained native AFS profile; exact-point preparation and amendment evidence preserved")
    elif args.command == "solve":
        run_afs_case(args.case_dir, args.ads_root, export_model=not args.skip_export)
        print("Completed the retained fullwave AFS execution; numerical qualification remains separate")
    else:
        export_afs(args.case_dir)
        print("Exported actual discrete and ADS-derived dense networks separately; no resampling performed")


if __name__ == "__main__":
    main()
